#!/usr/bin/env python3
"""Automatically add MOS region outputs/specs to a Cadence ADE Maestro setup.

Run from the same working directory from which you normally launch Virtuoso:

    ./regions.py LIBRARY CELL

The script opens LIBRARY/CELL/maestro, finds every test with an enabled DC
analysis, traverses LIBRARY/CELL/schematic and its schematic hierarchy, and
adds plotted region outputs with the ADE specification `tol 2 0.1` (target 2, tolerance 0.1%).

IMPORTANT:
  - This configures ADE outputs; it does not run simulations or create PNGs.
  - Close the target ADE Maestro view before running to avoid edit locks.
  - OP() is used by default (scalar operating point at each design point).
    Use --sweep for OS() (region waveform across a Spectre DC sweep).
  - Only devices whose cell names match --mos-pattern are recognized;
    foundry MOS names differ, so customize the regex for your PDK.
  - Hierarchical names in calculator expressions depend on your netlisting
    conventions; verify a hierarchical output against the ADE Calculator.
"""
from __future__ import print_function
import argparse
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

# SKILL runs inside the licensed Virtuoso process.  The Python wrapper only
# supplies arguments and launches it; Python does not parse proprietary PSF.
SKILL = r'''
; Generated by regions.py.  No PDK or Spectre netlist files are edited.
rrDevices = nil

procedure(rrIsMosName(cell)
  and(cell pcreMatchp("__REGEX__" lowerCase(cell)))
)

procedure(rrWalk(lib cell prefix ancestors depth)
  let((cv childLib childCell inst path key)
    when(depth <= __DEPTH__
      key = strcat(lib ":" cell)
      unless(member(key ancestors)
        cv = dbOpenCellViewByType(lib cell "schematic" nil "r")
        when(cv
          foreach(inst cv~>instances
            when(inst~>master
              childLib  = inst~>master~>libName
              childCell = inst~>master~>cellName
              path = strcat(prefix "/" inst~>name)
              cond(
                (rrIsMosName(childCell)
                  unless(member(path rrDevices)
                    rrDevices = cons(path rrDevices)
                  )
                )
                (t
                  ; A symbol with a matching schematic may contain more MOS.
                  rrWalk(childLib childCell path cons(key ancestors) add1(depth))
                )
              )
            )
          )
        )
      )
    )
  )
)

procedure(rrMain(lib cell view)
  let((session sdb tests test analyses outputs existing path outName expr added
       skipped ok specOk duplicate ntests ndevs o)
    printf("REGIONS: opening %s/%s/%s\n" lib cell view)
    session = maeOpenSetup(lib cell view)
    unless(session
      error("REGIONS: could not open Maestro; check cds.lib, cell/view and edit locks\n")
    )
    sdb = axlGetMainSetupDB(session)
    unless(sdb error("REGIONS: no Maestro setup database\n"))
    tests = cadr(axlGetTests(sdb))
    unless(tests
      error("REGIONS: this Maestro view has no tests\n")
    )
    rrWalk(lib cell "" nil 0)
    rrDevices = sort(rrDevices 'alphalessp)
    ndevs = length(rrDevices)
    printf("REGIONS: found %d MOS schematic instances\n" ndevs)
    when(ndevs == 0
      printf("REGIONS: MOS cell-name regex may need customization for the PDK\n")
    )
    ntests = 0
    added = 0
    skipped = 0
    foreach(test tests
      analyses = maeGetEnabledAnalysis(test ?session session)
      when(or(member("dc" analyses) member('dc analyses)
              member("dcOp" analyses) member("dcop" analyses))
        ntests = ntests + 1
        printf("REGIONS: DC-enabled test %s\n" test)
        outputs = maeGetTestOutputs(test ?session session)
        existing = nil
        foreach(o outputs
          when(o~>name existing = cons(o~>name existing))
        )
        foreach(path rrDevices
          ; Build output names from hierarchy, e.g. /I0/M3 -> region_I0_M3
          outName = strcat("region_" buildString(parseString(path "/") "_"))
          expr = sprintf(nil "__FUNCTION__(\"%s\" \"region\")" path)
          duplicate = member(outName existing)
          cond(
            (duplicate
              skipped = skipped + 1
              printf("REGIONS:   existing %s (will refresh spec)\n" outName)
              ok = t
            )
            (t
              ok = axlAddOutputExpr(session test outName
                        ?expr expr ?evalType "point" ?plot t ?save nil)
              when(ok
                added = added + 1
                existing = cons(outName existing)
              )
            )
          )
          when(ok
            ; Cadence ADE 'tol' values are TARGET:PERCENT, so 2:0.1 means
            ; region 2 (saturation) with +/- 0.1% tolerance.
            specOk = axlAddSpecToOutput(sdb test outName ?tol 2:0.1)
            unless(specOk
              printf("REGIONS: WARNING: couldn't set tol spec: %s/%s\n" test outName)
            )
          )
          unless(ok
            printf("REGIONS: WARNING: couldn't create %s/%s\n" test outName)
          )
        )
      )
    )
    printf("REGIONS: %d DC tests, %d new outputs, %d existing outputs\n"
           ntests added skipped)
    when(ntests == 0
      printf("REGIONS: no enabled DC analysis. No output changes made.\n")
    )
    when(ntests > 0
      maeSaveSetup(?session session)
      printf("REGIONS: requested Maestro setup save. Check CIW/CDS.log for warnings.\n")
    )
    maeCloseSession(?session session ?forceClose t)
    t
  )
)

rrMain("__LIB__" "__CELL__" "__VIEW__")
exit()
'''


def q_skill(s):
    """Encode a Python string as a quoted SKILL string's payload."""
    return s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')


def build_skill(args):
    for label, value in [('library', args.library), ('cell', args.cell), ('view', args.view)]:
        if not re.match(r'^[A-Za-z0-9_.$+@:-]+$', value):
            raise ValueError('Unsafe or unexpected {} name: {!r}'.format(label, value))
    # The expression will run against lowerCase(cell).  Double quotes are
    # forbidden here to avoid breaking generated SKILL string syntax.
    if '"' in args.mos_pattern or '\n' in args.mos_pattern:
        raise ValueError('--mos-pattern must not contain a quote or newline')
    content = SKILL
    for old, new in [('__LIB__', q_skill(args.library)),
                     ('__CELL__', q_skill(args.cell)),
                     ('__VIEW__', q_skill(args.view)),
                     ('__REGEX__', q_skill(args.mos_pattern)),
                     ('__DEPTH__', str(args.depth)),
                     ('__FUNCTION__', 'OS' if args.sweep else 'OP')]:
        content = content.replace(old, new)
    return content


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('library', help='Virtuoso library containing Maestro and the schematic')
    p.add_argument('cell', help='Cell with a maestro view and schematic')
    p.add_argument('--view', default='maestro', help='ADE view name (default: maestro)')
    p.add_argument('--sweep', action='store_true', help='Use OS() for a Spectre DC sweep; default OP()')
    p.add_argument('--depth', type=int, default=12, help='Maximum schematic hierarchy recursion (default 12)')
    p.add_argument('--mos-pattern', default=r'(nmos|pmos|nfet|pfet|nch|pch|nmos4|pmos4)',
                   help='Case-insensitive SKILL regex for MOS master cell names')
    p.add_argument('--dry-run', action='store_true', help='Generate SKILL in current directory without running Virtuoso')
    p.add_argument('--skill-file', help='Write generated SKILL to specified path (also run unless --dry-run)')
    args = p.parse_args(argv)
    if not (0 <= args.depth <= 64):
        p.error('--depth must be between 0 and 64')
    try:
        skill = build_skill(args)
    except ValueError as e:
        p.error(str(e))
    root = Path(os.getcwd())
    if not args.dry_run and not shutil.which('virtuoso'):
        print('ERROR: virtuoso not found on PATH. Run in your Cadence shell/environment.', file=sys.stderr)
        return 2
    if args.skill_file or args.dry_run:
        skill_path = Path(args.skill_file or ('regions_{}_{}.il'.format(args.library, args.cell))).resolve()
        skill_path.write_text(skill, encoding='utf8')
        print('Generated:', skill_path)
        if args.dry_run:
            return 0
        return run_skill(skill_path, root)
    with tempfile.TemporaryDirectory(prefix='regions_') as d:
        path = Path(d) / 'regions.il'
        path.write_text(skill, encoding='utf8')
        return run_skill(path, root)


def run_skill(skill_path, root):
    print('Opening Virtuoso in headless mode, using Cadence setup in:', root)
    print('Close any GUI ADE window editing this Maestro view before running.')
    code = subprocess.call(['virtuoso', '-nograph', '-restore', str(skill_path)], cwd=str(root))
    if code:
        print('Virtuoso returned status {}. Inspect its console/CDS log for REGIONS diagnostics.'.format(code), file=sys.stderr)
    return code


if __name__ == '__main__':
    sys.exit(main())
