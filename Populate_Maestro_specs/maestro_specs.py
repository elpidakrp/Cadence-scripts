#!/usr/bin/env python3
"""Configure MOS operating-point outputs in Cadence Maestro from specs.txt.

Run from your Virtuoso launch directory:

    ./maestro_specs.py LIBRARY CELL
    ./maestro_specs.py LIBRARY CELL --sweep
    ./maestro_specs.py LIBRARY CELL --specs /path/to/specs.txt
    ./maestro_specs.py LIBRARY CELL --dry-run

The script creates specs.txt with defaults if it does not already exist.
Change any [metric] section to enable/disable outputs, customize calculator
expressions, or set/unset tolerance and range specs.

Config example:

    [region]
    enabled = yes
    expression = {op}("{device}" "region")
    spec = tol 2 0.1
    plot = yes

    [gm_id]
    enabled = yes
    expression = {op}("{device}" "gmoverid")
    spec = range 5 25
    plot = yes

    [vsat_margin]
    enabled = no
    expression = {op}("{device}" "vsat_marg")
    spec = none
    plot = yes

"{device}" becomes an instance path such as /I0/M1. "{op}" becomes OP
normally, or OS with --sweep. Use either in custom calculator expressions.
Each enabled entry creates a named output for every detected MOSFET in every
Maestro test with DC analysis enabled. Disable to remove those outputs.
Setting spec=none removes its existing spec, keeping the output.

To ensure config changes really take effect, existing script-named outputs
are DELETED AND RECREATED each time, including unchanged outputs. Other ADE
outputs are not touched. Keep a backup of your Maestro setup; close its GUI
before making changes. No simulations are run and no PNGs are generated.
"""
from __future__ import print_function

import argparse
import configparser
import math
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path


DEFAULT_SPECS = '''# MOS output configuration for regions.py
# Expressions are Cadence Calculator strings, NOT Python expressions.
# {device} -> /I0/M1 ; {op} -> OP (or OS with --sweep).
# 'enabled = no' removes the corresponding script-named output.
# 'spec = none' clears its previous specification but keeps the output.
# 'spec = tol TARGET PERCENT'  e.g. tol 2 0.1 means 2 +/- 0.1%
# 'spec = range MIN MAX'       e.g. range 5 25 means 5 <= value <= 25
# 'plot = no' keeps an output without enabling its plot.

[region]
enabled = yes
expression = {op}("{device}" "region")
spec = tol 2 0.1
plot = yes

[gm_id]
enabled = yes
expression = {op}("{device}" "gmoverid")
spec = none
plot = yes

[vsat_margin]
enabled = yes
expression = {op}("{device}" "vsat_marg")
spec = none
plot = yes
'''

SKILL = r'''
; Generated by regions.py. Edits only Maestro Outputs Setup, not the PDK.
rrDevices = nil

procedure(rrIsMosName(cell)
  and(cell pcreMatchp("__REGEX__" lowerCase(cell)))
)

procedure(rrWalk(lib cell prefix ancestors depth)
  let((cv childLib childCell inst path key)
    when(depth <= __DEPTH__
      key = strcat(lib ":" cell)
      unless(member(key ancestors)
        cv = dbOpenCellViewByType(lib cell "schematic" nil "r")
        when(cv
          foreach(inst cv~>instances
            when(inst~>master
              childLib = inst~>master~>libName
              childCell = inst~>master~>cellName
              path = strcat(prefix "/" inst~>name)
              cond(
                (rrIsMosName(childCell)
                  unless(member(path rrDevices)
                    rrDevices = cons(path rrDevices)
                  )
                )
                (t
                  rrWalk(childLib childCell path cons(key ancestors) add1(depth))
                )
              )
            )
          )
        )
      )
    )
  )
)

; Use symbol 'rrDevice for the instance path so format strings never
; interpret a literal percent sign from the user's calculator expression.
procedure(rrExpandExpr(parts path)
  let((expr)
    expr = ""
    foreach(part parts
      expr = strcat(expr if(eq(part 'rrDevice) then path else part))
    )
    expr
  )
)

procedure(rrMain(lib cell view)
  let((session sdb tests test analyses outputs existing path outName expr
       ntests ndevs added replaced removed failed delOk addOk specOk
       metrics metric metricName enabled plotParts specType a b pieces
       plotFlag evalMode prior)
    printf("REGIONS: opening %s/%s/%s\n" lib cell view)
    session = maeOpenSetup(lib cell view)
    unless(session
      error("REGIONS: cannot open Maestro setup; check cds.lib and edit locks\n")
    )
    sdb = axlGetMainSetupDB(session)
    unless(sdb error("REGIONS: no Maestro setup database\n"))
    tests = cadr(axlGetTests(sdb))
    unless(tests error("REGIONS: Maestro view has no tests\n"))
    rrWalk(lib cell "" nil 0)
    rrDevices = sort(rrDevices 'alphalessp)
    ndevs = length(rrDevices)
    printf("REGIONS: found %d MOS devices\n" ndevs)
    when(ndevs == 0
      printf("REGIONS: WARNING: check --mos-pattern for your PDK\n")
    )
    metrics = __METRICS__
    evalMode = "point"
    ntests = 0
    added = 0
    replaced = 0
    removed = 0
    failed = 0
    foreach(test tests
      analyses = maeGetEnabledAnalysis(test ?session session)
      when(or(member("dc" analyses) member('dc analyses)
              member("dcOp" analyses) member("dcop" analyses))
        ntests = ntests + 1
        printf("REGIONS: DC test %s\n" test)
        outputs = maeGetTestOutputs(test ?session session)
        existing = nil
        foreach(prior outputs
          when(prior~>name
            existing = cons(prior~>name existing)
          )
        )
        foreach(path rrDevices
          foreach(metric metrics
            metricName = car(metric)
            enabled = cadr(metric)
            plotFlag = caddr(metric)
            specType = car(cdddr(metric))
            a = cadr(cdddr(metric))
            b = caddr(cdddr(metric))
            pieces = car(cdddr(cdddr(metric)))
            outName = strcat(metricName "_" buildString(parseString(path "/") "_"))
            ; Recreate outputs each run. This clears old specs and refreshes
            ; expressions/plot flags even when the name has not changed.
            delOk = t
            when(member(outName existing)
              delOk = axlDeleteOutput(session test outName ?type "expr")
              if(eq(delOk t) then
                existing = remove(outName existing)
                if(enabled then
                  replaced = replaced + 1
                else
                  removed = removed + 1
                )
              else
                failed = failed + 1
                printf("REGIONS: ERROR deleting %s/%s: %L\n" test outName delOk)
              )
            )
            when(and(enabled eq(delOk t))
              expr = rrExpandExpr(pieces path)
              addOk = axlAddOutputExpr(session test outName
                         ?expr expr ?evalType evalMode ?plot plotFlag ?save nil)
              if(eq(addOk t) then
                added = added + 1
                cond(
                  (equal(specType "tol")
                    specOk = axlAddSpecToOutput(sdb test outName ?tol a:b)
                  )
                  (equal(specType "range")
                    specOk = axlAddSpecToOutput(sdb test outName ?range a:b)
                  )
                  (t specOk = t)
                )
                unless(eq(specOk t)
                  failed = failed + 1
                  printf("REGIONS: ERROR setting spec on %s/%s: %L\n"
                         test outName specOk)
                )
              else
                failed = failed + 1
                printf("REGIONS: ERROR adding %s/%s: %L\n" test outName addOk)
              )
            )
          )
        )
      )
    )
    printf("REGIONS: %d DC tests, %d outputs added (%d replaced), %d disabled removed, %d errors\n"
           ntests added replaced removed failed)
    when(ntests == 0
      printf("REGIONS: no DC-enabled tests found; no changes to save.\n")
    )
    if(failed == 0 then
      when(ntests > 0
        maeSaveSetup(?session session)
        printf("REGIONS: Maestro setup saved. Rerun DC simulations for new results.\n")
      )
    else
      printf("REGIONS: ERROR: save skipped because of failures; inspect output.\n")
    )
    maeCloseSession(?session session ?forceClose t)
    if(failed == 0 then t else nil)
  )
)

rrResult = rrMain("__LIB__" "__CELL__" "__VIEW__")
if(rrResult then exit(0) else exit(1))
'''


NAME = re.compile(r'^[A-Za-z][A-Za-z0-9_]*$')
LCV_NAME = re.compile(r'^[A-Za-z0-9_.$+@:-]+$')


def q_skill(value):
    """Escape a string for a quoted Cadence SKILL literal."""
    return (value.replace('\\', '\\\\').replace('"', '\\"')
            .replace('\n', '\\n').replace('\r', '\\r'))


def num_str(value):
    return format(value, '.12g')


def read_spec(spec, section):
    parts = spec.strip().split()
    if not parts or parts[0].lower() in ('none', 'off', 'unset'):
        if len(parts) > 1:
            raise ValueError('[{}] spec: expected just none/off/unset'.format(section))
        return ('none', 0.0, 0.0)
    kind = parts[0].lower()
    if kind not in ('tol', 'range') or len(parts) != 3:
        raise ValueError('[{}] spec: use none, tol TARGET PERCENT or range MIN MAX'.format(section))
    try:
        a, b = float(parts[1]), float(parts[2])
    except ValueError:
        raise ValueError('[{}] spec: numbers required'.format(section))
    if not (math.isfinite(a) and math.isfinite(b)):
        raise ValueError('[{}] spec: finite numbers required'.format(section))
    if kind == 'tol' and b < 0:
        raise ValueError('[{}] spec: tolerance percent cannot be negative'.format(section))
    if kind == 'range' and a > b:
        raise ValueError('[{}] spec: MIN cannot exceed MAX'.format(section))
    return (kind, a, b)


def load_metrics(specs_path, sweep):
    parser = configparser.ConfigParser(interpolation=None, inline_comment_prefixes=None)
    parser.optionxform = str.lower
    with specs_path.open('r', encoding='utf-8') as f:
        parser.read_file(f)
    if not parser.sections():
        raise ValueError('specs.txt has no [metric] sections')
    metrics = []
    for section in parser.sections():
        if not NAME.fullmatch(section):
            raise ValueError('Invalid metric section name {!r}'.format(section))
        allowed = {'enabled', 'expression', 'spec', 'plot'}
        extras = set(parser.options(section)) - allowed
        if extras:
            raise ValueError('[{}] unknown options: {}'.format(section, ', '.join(sorted(extras))))
        enabled = parser.getboolean(section, 'enabled', fallback=True)
        plot = parser.getboolean(section, 'plot', fallback=True)
        expression = parser.get(section, 'expression', fallback='').strip()
        if enabled and not expression:
            raise ValueError('[{}] expression is required when enabled=yes'.format(section))
        if expression and '{device}' not in expression:
            raise ValueError('[{}] expression must contain {{device}}'.format(section))
        if '\n' in expression or '\r' in expression:
            raise ValueError('[{}] expression must be one line'.format(section))
        expression = expression.replace('{op}', 'OS' if sweep else 'OP')
        if '{' in expression.replace('{device}', '') or '}' in expression.replace('{device}', ''):
            raise ValueError('[{}] unknown template token; use {{op}} and {{device}}'.format(section))
        spec = read_spec(parser.get(section, 'spec', fallback='none'), section)
        metrics.append({'name': section, 'enabled': enabled, 'plot': plot,
                        'expr': expression, 'spec': spec})
    return metrics


def skill_metric(m):
    parts = m['expr'].split('{device}')
    tokens = []
    for i, part in enumerate(parts):
        if i:
            tokens.append("'rrDevice")
        tokens.append('"{}"'.format(q_skill(part)))
    kind, a, b = m['spec']
    return 'list("{}" {} {} "{}" {} {} list({}))'.format(
        q_skill(m['name']), 't' if m['enabled'] else 'nil',
        't' if m['plot'] else 'nil', kind, num_str(a), num_str(b),
        ' '.join(tokens))


def build_skill(args, metrics):
    for field in ('library', 'cell', 'view'):
        value = getattr(args, field)
        if not LCV_NAME.fullmatch(value):
            raise ValueError('Invalid {} name {!r}'.format(field, value))
    if '\n' in args.mos_pattern or '"' in args.mos_pattern:
        raise ValueError('--mos-pattern cannot include quotes or newlines')
    metric_code = 'list(\n      {}\n    )'.format('\n      '.join(skill_metric(m) for m in metrics))
    skill = SKILL
    for token, value in [
        ('__LIB__', q_skill(args.library)),
        ('__CELL__', q_skill(args.cell)),
        ('__VIEW__', q_skill(args.view)),
        ('__REGEX__', q_skill(args.mos_pattern)),
        ('__DEPTH__', str(args.depth)),
        ('__METRICS__', metric_code),
    ]:
        skill = skill.replace(token, value)
    return skill


def run_skill(path, cwd):
    print('Opening Virtuoso headlessly in {}'.format(cwd), flush=True)
    print('Close GUI windows editing this Maestro view before running.', flush=True)
    status = subprocess.call(['virtuoso', '-nograph', '-restore', str(path)], cwd=str(cwd))
    if status:
        print('ERROR: Virtuoso returned {}; inspect CDS.log / REGIONS messages.'.format(status), file=sys.stderr)
    return status


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('library', help='Virtuoso library name')
    parser.add_argument('cell', help='Cell containing maestro and schematic views')
    parser.add_argument('--view', default='maestro', help='ADE setup view (default: maestro)')
    parser.add_argument('--specs', default='specs.txt', help='Configuration path (default: ./specs.txt)')
    parser.add_argument('--init-specs', action='store_true', help='Create default specs.txt and exit (never overwrites)')
    parser.add_argument('--sweep', action='store_true', help='Use OS() instead of OP()')
    parser.add_argument('--depth', type=int, default=12, help='Maximum schematic hierarchy depth')
    parser.add_argument('--mos-pattern', default=r'(nmos|pmos|nfet|pfet|nch|pch|nmos4|pmos4)',
                        help='Case-insensitive SKILL regex matching MOS master cell names')
    parser.add_argument('--dry-run', action='store_true', help='Write SKILL but do not invoke Virtuoso')
    parser.add_argument('--skill-file', help='Save generated SKILL to this path')
    args = parser.parse_args(argv)
    if not (0 <= args.depth <= 64):
        parser.error('--depth must be between 0 and 64')
    specs_path = Path(args.specs).expanduser().resolve()
    if not specs_path.exists():
        specs_path.parent.mkdir(parents=True, exist_ok=True)
        specs_path.write_text(DEFAULT_SPECS, encoding='utf-8')
        print('Created default config:', specs_path)
    if args.init_specs:
        print('Edit this file to set/clear outputs and specs:', specs_path)
        return 0
    try:
        metrics = load_metrics(specs_path, args.sweep)
        skill = build_skill(args, metrics)
    except (ValueError, configparser.Error, OSError) as exc:
        parser.error(str(exc))
    print('Configuration:', specs_path)
    for m in metrics:
        kind, a, b = m['spec']
        status = 'ON' if m['enabled'] else 'OFF (remove)'
        spec_txt = kind if kind == 'none' else '{} {} {}'.format(kind, num_str(a), num_str(b))
        print('  {:<14} {:<13} plot={}  spec={}'.format(
            m['name'], status, 'yes' if m['plot'] else 'no', spec_txt))
    if not args.dry_run and not shutil.which('virtuoso'):
        print('ERROR: virtuoso not on PATH; run in Cadence environment.', file=sys.stderr)
        return 2
    cwd = Path.cwd()
    if args.skill_file or args.dry_run:
        path = Path(args.skill_file or 'regions_{}_{}.il'.format(args.library, args.cell)).resolve()
        path.write_text(skill, encoding='utf-8')
        print('Generated SKILL:', path)
        if args.dry_run:
            return 0
        return run_skill(path, cwd)
    with tempfile.TemporaryDirectory(prefix='regions_') as tmpdir:
        path = Path(tmpdir) / 'regions.il'
        path.write_text(skill, encoding='utf-8')
        return run_skill(path, cwd)


if __name__ == '__main__':
    sys.exit(main())
